#!/usr/bin/env node
// Provisions one device key per reader through the EXISTING backend API and writes the ESP32 reader table.
//   1. POST /api/auth/login            (System Administrator)
//   2. GET  /api/stages                (reader codes + department id/name, straight from the database)
//   3. PUT  /api/readers/:id/key       (existing admin endpoint; backend stores only the SHA-256)
// Output: firmware/TexTracerRFID/reader_keys.h   (keys are written to the file only, never printed)
//
// Usage:  node provision_reader_keys.mjs [--api http://localhost:5000/api] [--out <file>] [--force]
//         ADMIN_EMAIL / ADMIN_PASSWORD env vars skip the prompts.
// Safety: refuses to overwrite a reader_keys.h that is no longer the placeholder (so keys are not rotated by accident).
//         Re-keying a reader invalidates its previous key, so run this once, then flash the ESP32.
import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { createInterface } from "node:readline/promises";

const here = dirname(fileURLToPath(import.meta.url));
const arg = (n, d) => { const i = process.argv.indexOf(n); return i > 0 ? process.argv[i + 1] : d; };
const API = (arg("--api", "http://localhost:5000/api")).replace(/\/$/, "");
const OUT = resolve(arg("--out", resolve(here, "../firmware/TexTracerRFID/reader_keys.h")));
const MARKER = "TEXTRACER_PLACEHOLDER_KEYS";

async function call(method, path, body, token) {
  const r = await fetch(API + path, {
    method,
    headers: { "Content-Type": "application/json", ...(token ? { Authorization: `Bearer ${token}` } : {}) },
    body: body ? JSON.stringify(body) : undefined,
  });
  const j = await r.json().catch(() => null);
  if (!r.ok || !j?.success) throw new Error(`${method} ${path} -> HTTP ${r.status} ${j?.error?.code ?? ""} ${j?.error?.message ?? ""}`);
  return j.data;
}

const FORCE = process.argv.includes("--force");
if (!FORCE && existsSync(OUT) && !readFileSync(OUT, "utf8").includes(MARKER)) {
  console.error(`Refusing to overwrite ${OUT}: it already contains provisioned keys.\n` +
    `Run again with --force only if you really want to issue NEW keys (the old keys stop working; re-flash the ESP32 afterwards).`);
  process.exit(2);
}

let email = process.env.ADMIN_EMAIL, password = process.env.ADMIN_PASSWORD;
if (!email || !password) {
  const rl = createInterface({ input: process.stdin, output: process.stdout });
  email ||= await rl.question("System Administrator email: ");
  password ||= await rl.question("Password (will be visible): ");
  rl.close();
}

const { token, user } = await call("POST", "/auth/login", { email, password });
if (user.role !== "system_admin") throw new Error(`Logged in as ${user.role}; key provisioning needs system_admin.`);

const stages = await call("GET", "/stages", undefined, token);
const rows = [];
for (const s of stages) for (const r of s.readers) rows.push({ id: r.id, code: r.code, active: r.isActive, stage: s.code, deptId: s.departmentId, dept: s.department, hasKey: r.hasDeviceKey });
rows.sort((a, b) => a.id - b.id);
if (rows.length !== 9) console.warn(`Warning: backend has ${rows.length} readers; the firmware is wired for 9.`);

const lines = [];
for (const r of rows) {
  if (!r.active) { console.warn(`Skipping inactive reader ${r.code}`); continue; }
  const k = await call("PUT", `/readers/${r.id}/key`, undefined, token);
  console.log(`Provisioned key for ${k.readerCode} (reader id ${k.readerId}, department ${r.deptId} ${r.dept}${r.hasKey ? ", previous key replaced" : ""})`);
  lines.push(`  {${JSON.stringify(r.code)}, ${JSON.stringify(r.stage)}, ${r.deptId}, ${JSON.stringify(r.dept)}, ${JSON.stringify(k.deviceKey)}},`);
}

const header = `// GENERATED by tools/provision_reader_keys.mjs on ${new Date().toISOString()} from ${API}
// Contains SECRET device keys. Do not commit or share this file.
// Order = physical reader number 1..${lines.length} (reader #1 -> SS GPIO 27, #2 -> 12, #3 -> 15, #4 -> 2, #5 -> 4, #6 -> 16, #7 -> 5, #8 -> 17, #9 -> 21).
#pragma once

struct ReaderDef {
  const char* code;
  const char* stage;
  int         departmentId;
  const char* department;
  const char* key;
};

static const ReaderDef READER_DEFS[] = {
${lines.join("\n")}
};
`;
writeFileSync(OUT, header, { mode: 0o600 });
console.log(`\nWrote ${OUT}\nKeys are in that file only. Now flash firmware/TexTracerRFID to the ESP32.`);
